// Package dbaverify verifies devicebasedauth.org ("DBA") device credentials in Go.
//
// It is a port of the JavaScript reference library @devicebasedauth/verify
// (packages/verify/src in this repository) and follows spec/credential.md and
// spec/evaluation.md. It uses only the standard library so that it can be vendored into any
// relying party without pulling in a JOSE stack.
//
// The pieces, from low to high level:
//
//   - JOSE: base64url, ES256 compact JWS verification, RFC 7638 JWK thumbprints ([VerifyJWS],
//     [JWKThumbprint]).
//   - Credentials and DPoP proofs: [VerifyCredential] and [VerifyProof], which fail with a
//     [*VerificationError] whose Code matches the JavaScript library.
//   - Status lists (revocation): [DecodeStatusList] and [GetBit].
//   - Grant evaluation: [EvaluateGrants], the offline policy decision.
//   - A caching [Verifier] that fetches the issuer's JWKS and status lists and decides whole
//     *http.Request values, plus [SiteAuth] and middleware for sites that accept DBA
//     credentials as API keys.
//
// Faithfulness matters more than idiom here: the conformance vectors in spec/vectors are
// generated by the JavaScript implementation, and every implementation must produce the same
// decisions and reason codes. Where JavaScript semantics leak into the result (for example the
// order of unknown_constraint reasons follows JavaScript object key order) this package
// reproduces them; JSON is therefore parsed with [ParseJSON] into [*Object] values that keep
// member order instead of into Go maps.
package dbaverify
